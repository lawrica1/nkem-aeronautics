import { firmLabel } from "../firms/firms.constants.js";

export function serializeUser(user) {
  return {
    id: user.id,
    role: user.role,
    sector: user.sector,
    accountType: user.accountType,
    country: user.country,
    surname: user.surname,
    name: user.name,
    sex: user.sex,
    telephone: user.telephone,
    email: user.email,
    address: user.address,
    region: user.region,
    district: user.district,
    crop: user.crop,
    otherCrop: user.otherCrop,
    firm: user.firm,
    firmLabel: firmLabel(user.firm, user.otherFirm),
    otherFirm: user.otherFirm,
    wildlifeOrg: user.wildlifeOrg,
    wildlifeRole: user.wildlifeRole,
    realEstatePurpose: user.realEstatePurpose,
    govAgencyName: user.govAgencyName,
    govAuthorizingOfficer: user.govAuthorizingOfficer,
    miningOrg: user.miningOrg,
    miningRole: user.miningRole,
    organizationId: user.organizationId,
    organizationName: user.organization?.name ?? null,
    identificationNumber: user.identificationNumber,
    isVerified: user.isVerified,
    isProfileComplete: user.isProfileComplete ?? false,
    profilePhotoUrl: user.profilePhotoUrl ?? null,
    createdAt: user.createdAt?.toISOString?.() ?? user.createdAt,
    updatedAt: user.updatedAt?.toISOString?.() ?? user.updatedAt,
  };
}
